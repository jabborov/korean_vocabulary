"""Split the big data files into one small file per topic: topics/NNNN.js.

Source files (edit these, then run `python3 build_topics.py`):
  examples.js     Korean example sentences, topic -> word -> [A1, A2, B1, B2, C1, C2]
  examples_uz.js  Uzbek translations of those sentences, same shape
  relations.js    synonyms / opposites, topic -> word -> {syn: [...], ant: [...]}

Each topics/NNNN.js holds only that topic's part of all three, so a topic page
(and the random-word card) loads ~40 KB instead of ~5 MB. The pages load them with loader.js.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(ROOT, 'topics')
SOURCES = [('VOCAB_EXAMPLES', 'examples.js'),
           ('VOCAB_EXAMPLES_UZ', 'examples_uz.js'),
           ('VOCAB_RELATIONS', 'relations.js')]


def load(name, var):
    text = open(os.path.join(ROOT, name), encoding='utf-8').read()
    start = text.index(f'window.{var} = ') + len(f'window.{var} = ')
    return json.loads(text[start:].rstrip().rstrip(';'))


def main():
    data = open(os.path.join(ROOT, 'data.js'), encoding='utf-8').read()
    topics = re.findall(r'\n\s*"(\d{4})":\s*\{', data)
    sources = [(var, load(name, var)) for var, name in SOURCES]
    os.makedirs(OUT, exist_ok=True)
    for old in os.listdir(OUT):                      # drop files of topics that no longer exist
        if old.endswith('.js') and old[:-3] not in topics:
            os.remove(os.path.join(OUT, old))
    for k in topics:
        lines = [f'// Topic {k}: example sentences (A1–C2), their Uzbek translations, and synonyms/opposites.',
                 '// Generated by build_topics.py from examples.js, examples_uz.js and relations.js — do not edit.']
        for var, src in sources:
            part = src.get(k, {})
            body = ',\n'.join(f'  {json.dumps(w, ensure_ascii=False)}: {json.dumps(v, ensure_ascii=False)}'
                              for w, v in part.items())
            lines.append(f'(window.{var} = window.{var} || {{}})["{k}"] = {{\n{body}\n}};')
        text = '\n'.join(lines) + '\n'
        with open(os.path.join(OUT, f'{k}.js'), 'w', encoding='utf-8', newline='') as f:
            f.write(text.replace('\n', '\r\n'))
    print(f'wrote {len(topics)} files to topics/')


if __name__ == '__main__':
    main()
